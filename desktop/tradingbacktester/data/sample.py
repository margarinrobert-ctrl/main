@dataclass(frozen=True)
class SampleSpec:
    """One of the datasets shipped with a fresh workspace."""

    filename: str
    symbol: str
    timeframe: str
    n_bars: int
    seed: int
    start: str

    def describe(self) -> str:
        return f"{self.symbol} {self.timeframe}, {self.n_bars:,} synthetic bars"


#: The three bundled samples: one round-the-clock FX series, one intraday
#: futures series on a bounded session, and one daily equity series.  Between
#: them they exercise every path in the generator and every timeframe shape the
#: rest of the application has to cope with.
SAMPLE_SPECS: tuple[SampleSpec, ...] = (
    SampleSpec("SYNTHETIC_EURUSD_60m.csv", "EURUSD", "60m", 12_000, 101, "2023-01-02"),
    SampleSpec("SYNTHETIC_NQ_5m.csv", "NQ", "5m", 20_000, 202, "2024-01-02"),
    SampleSpec("SYNTHETIC_SPY_1D.csv", "SPY", "1D", 1_500, 303, "2019-01-02"),
)


def ensure_samples(workspace: Workspace | str | Path, force: bool = False) -> list[Path]:
    """Create the bundled sample files in the workspace if they are not there.

    Called on every start-up, so it is cheap when the files already exist: a
    sample is only regenerated when it is missing, or when ``force`` is set
    because the user asked for the originals back.

    Returns the paths of all three samples, whether or not they were written
    this time.  A sample that cannot be written is logged and skipped rather
    than stopping the application from starting -- the workspace may be on a
    read-only volume.
    """
    space = workspace if isinstance(workspace, Workspace) else Workspace(Path(workspace))
    folder = space.samples
    try:
        folder.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise StorageError(
            f"The samples folder could not be created at {folder}.",
            detail=repr(exc)) from exc

    written: list[Path] = []
    for spec in SAMPLE_SPECS:
        target = folder / spec.filename
        if target.exists() and not force:
            written.append(target)
            continue
        try:
            bars = generate_sample_data(spec.symbol, spec.timeframe, spec.n_bars,
                                        seed=spec.seed, start=spec.start,
                                        name=Path(spec.filename).stem)
            write_sample_csv(target, bars)
            written.append(target)
        except (DataError, StorageError) as exc:
            log.error("The sample %s could not be created: %s", spec.filename, exc)
        except Exception as exc:  # noqa: BLE001 - start-up must not be blocked
            log.exception("Unexpected failure generating the sample %s: %r",
                          spec.filename, exc)
    return written


def sample_paths(workspace: Workspace | str | Path) -> list[Path]:
    """Where the bundled samples live, whether or not they exist yet."""
    space = workspace if isinstance(workspace, Workspace) else Workspace(Path(workspace))
    return [space.samples / spec.filename for spec in SAMPLE_SPECS]


def describe_samples() -> Sequence[str]:
    """One line per bundled sample, for an about box or the log."""
    return [f"{spec.filename}: {spec.describe()}" for spec in SAMPLE_SPECS]


def is_synthetic(bars: BarSeries) -> bool:
    """True when a series was produced by this module.

    Reports and the window title use it to keep the SYNTHETIC label attached to
    results computed from generated data.
    """
    return bool(bars.meta.get("synthetic")) or bars.source == SYNTHETIC_SOURCE
