"""Synthetic market data that behaves like the real thing.

Every installation needs something to open on the first run, and the only
honest way to ship bars is to generate them.  The point of this module is that
the result should *look* right on a chart -- volatility that clusters, sessions
that are busy at the open and the close, trends that run and then stall, gaps
over the weekend, volume that spikes when price moves -- because a sample that
looks wrong teaches a user the wrong thing about the application.

It should also never be mistaken for real data.  So: every file starts with a
``# SYNTHETIC TEST DATA`` comment line, every generated file name carries the
word SYNTHETIC, and every :class:`BarSeries` produced here has
``meta["synthetic"] = True`` along with a plain-language warning string.

How the price process is put together
-------------------------------------

Log returns are the sum of three pieces plus noise:

``drift``
    A constant, calibrated from an annual return so a two-year sample of an
    equity index goes up by roughly what an equity index does.
``regime``
    A slow AR(1) component that switches between a *trending* mode (very
    persistent, so moves accumulate) and a *ranging* mode (fast reversion, so
    they cancel).  This is what makes a chart look like it has structure
    instead of being a pure random walk.
``volatility``
    A GARCH(1,1) variance -- quiet periods stay quiet, a big move makes the
    next move bigger -- multiplied by a time-of-day seasonality curve and a
    three-state volatility regime.  Shocks are Student-t with five degrees of
    freedom, standardised to unit variance, because normal tails produce a
    series with visibly too few outliers.

Each bar's high and low are then built by adding a strictly non-negative
excursion above and below the open/close body, which is what guarantees
``high >= max(open, close)`` and ``low <= min(open, close)`` for every bar
without any post-hoc repair.

Everything is drawn from one seeded :class:`numpy.random.Generator`, so the
same arguments always produce the same bars, on any machine.
"""

