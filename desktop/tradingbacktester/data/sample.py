def generate_sample_data(symbol: str | Instrument = "EURUSD",
                         timeframe: Timeframe | str = "1h",
                         n_bars: int = 5_000,
                         *,
                         seed: int = 20200102,
                         start: str | datetime | pd.Timestamp = DEFAULT_START,
                         start_price: float | None = None,
                         annual_volatility: float | None = None,
                         annual_drift: float | None = None,
                         name: str = "") -> BarSeries:
    """Generate a deterministic synthetic :class:`BarSeries`.

    Parameters
    ----------
    symbol:
        A symbol from the seeded catalogue, or a full :class:`Instrument`.
    timeframe:
        Bar duration, as a :class:`Timeframe` or anything
        :meth:`Timeframe.parse` accepts (``"5m"``, ``"60m"``, ``"1D"``).
    n_bars:
        How many bars to produce.
    seed:
        Anything drawn here comes from ``numpy.random.default_rng(seed)``, so
        the same arguments always give the same bars.
    start:
        Date of the first bar.  Fixed by default so output is reproducible.
    start_price, annual_volatility, annual_drift:
        Override the symbol's character.  Volatility and drift are annualised
        fractions -- ``0.20`` is 20 percent.
    name:
        Dataset name recorded in ``meta``; defaults to ``SYNTHETIC <symbol> <tf>``.

    Returns
    -------
    BarSeries
        With ``meta["synthetic"] = True`` and every OHLC relationship valid.
    """
    instrument = _resolve_instrument(symbol)
    tf = timeframe if isinstance(timeframe, Timeframe) else Timeframe.parse(str(timeframe))
    count = _as_int(n_bars, "number of bars")
    if count < 2:
        raise DataError("A sample dataset needs at least two bars.")
    if count > 5_000_000:
        raise DataError("That is more sample bars than this generator will make "
                        "in one go; ask for five million or fewer.")

    profile = session_for(instrument)
    character = character_for(instrument)
    price0 = _as_float(start_price if start_price is not None
                       else character.start_price, "starting price")
    ann_vol = _as_float(annual_volatility if annual_volatility is not None
                        else character.annual_volatility, "annual volatility")
    ann_drift = _as_float(annual_drift if annual_drift is not None
                          else character.annual_drift, "annual drift")
    if price0 <= 0:
        raise DataError("A starting price must be greater than zero.")
    if ann_vol <= 0:
        raise DataError("Annual volatility must be greater than zero.")

    rng = np.random.default_rng(_as_int(seed, "seed"))
    ts = _session_timestamps(profile, tf, count, start)

    # Local wall-clock position of every bar, for seasonality and day breaks.
    local = pd.to_datetime(ts, utc=True).tz_convert(profile.timezone)
    minutes = (local.hour.to_numpy(dtype="float64") * 60.0
               + local.minute.to_numpy(dtype="float64"))
    day_id = np.asarray(local.normalize().tz_localize(None), dtype="datetime64[D]")
    new_day = np.empty(count, dtype=bool)
    new_day[0] = False  # nothing to gap from on the first bar
    new_day[1:] = day_id[1:] != day_id[:-1]

    intraday = tf.unit in (TimeframeUnit.SECOND, TimeframeUnit.MINUTE, TimeframeUnit.HOUR)
    if intraday:
        vol_season, turnover_season = _intraday_profiles(minutes, profile, instrument)
        bars_per_day = _bars_per_session(profile, tf)
    else:
        vol_season = np.ones(count)
        turnover_season = np.ones(count)
        bars_per_day = 1

    days_per_year = _WEEKDAYS_PER_YEAR if profile.round_the_clock else _TRADING_DAYS_PER_YEAR
    if tf.unit is TimeframeUnit.WEEK:
        bars_per_year = 52.0 / tf.multiplier
    elif tf.unit is TimeframeUnit.MONTH:
        bars_per_year = 12.0 / tf.multiplier
    elif intraday:
        bars_per_year = days_per_year * bars_per_day
    else:  # daily bars, possibly several days each
        bars_per_year = days_per_year / tf.multiplier
    bars_per_year = max(bars_per_year, 1.0)

    # The overnight gap carries a share of each day's variance rather than
    # being added on top of it, so shrink the per-bar volatility by that share:
    # a market that gaps 5 percent of the way to its daily range should not
    # also move a full day's worth inside the session.
    gap_share = _GAP_VARIANCE_SHARE_24H if profile.round_the_clock else _GAP_VARIANCE_SHARE
    sigma0 = ann_vol / math.sqrt(bars_per_year) / math.sqrt(1.0 + gap_share)
    # Log-return drift: subtracting half the variance makes the *arithmetic*
    # annual return come out at ``annual_drift`` rather than overshooting it.
    drift = (ann_drift - 0.5 * ann_vol * ann_vol) / bars_per_year

    returns, sigma_used, sigma_state = _return_path(rng, count, sigma0, drift, vol_season)
    gaps = _overnight_gaps(rng, new_day, sigma_state, bars_per_day, profile)

    log_start = math.log(price0)
    cumulative = np.cumsum(gaps + returns)
    close_log = log_start + cumulative
    open_log = log_start + (cumulative - returns)

    high_log, low_log = _intrabar_range(rng, open_log, close_log, sigma_used)

    open_ = np.exp(open_log)
    close = np.exp(close_log)
    high = np.exp(high_log)
    low = np.exp(low_log)
    volume = _volume(rng, returns, sigma_used, turnover_season,
                     character.daily_volume, bars_per_day, instrument)

    open_, high, low, close = _snap_to_tick(instrument, open_, high, low, close)

    bars = BarSeries(
        ts=ts, open=open_, high=high, low=low, close=close, volume=volume,
        instrument=instrument, timeframe=tf, source=SYNTHETIC_SOURCE,
        meta={
            "synthetic": True,
            "data_warning": SYNTHETIC_WARNING,
            "generator": "tradingbacktester.data.sample.generate_sample_data",
            "name": name or f"SYNTHETIC {instrument.symbol} {tf.label}",
            "seed": int(seed),
            "start": str(start),
            "annual_volatility": ann_vol,
            "annual_drift": ann_drift,
            "start_price": price0,
            "session": f"{profile.open_minute // 60:02d}:{profile.open_minute % 60:02d}"
                       f"-{profile.close_minute // 60:02d}:{profile.close_minute % 60:02d} "
                       f"{profile.timezone}",
            "generated_by": "Trading Backtester",
        },
    )
    log.info("Generated %s (seed %d)", bars.describe(), seed)
    return bars


def _as_int(value: Any, what: str) -> int:
    """Convert a caller's number, turning a bad one into a :class:`DataError`.

    The generator is driven from the UI, where every setting arrives as text;
    a raw ``ValueError`` from ``int()`` would reach the user as a traceback.
    """
    try:
        return int(value)
    except (TypeError, ValueError) as exc:
        raise DataError(f"The {what} must be a whole number, not '{value}'.",
                        detail=repr(exc)) from exc


def _as_float(value: Any, what: str) -> float:
    """Convert a caller's number, turning a bad one into a :class:`DataError`."""
    try:
        result = float(value)
    except (TypeError, ValueError) as exc:
        raise DataError(f"The {what} must be a number, not '{value}'.",
                        detail=repr(exc)) from exc
    if not math.isfinite(result):
        raise DataError(f"The {what} must be a finite number.")
    return result


def _resolve_instrument(symbol: str | Instrument) -> Instrument:
    """Accept a symbol or a full instrument; never hand back a shared object."""
    if isinstance(symbol, Instrument):
        return copy.deepcopy(symbol)
    key = str(symbol).strip().upper()
    if not key:
        raise DataError("A sample dataset needs a symbol.")
    seeded = default_instrument_for(key)
    if seeded is not None:
        return seeded
    log.info("No seeded contract specification for %s; using generic defaults", key)
    return Instrument(symbol=key)


def _return_path(rng: np.random.Generator, n: int, sigma0: float, drift: float,
                 vol_season: np.ndarray) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Log returns, the volatility that produced each one, and the regime level.

    The third array is the volatility *without* the time-of-day seasonality:
    it is what the overnight gap is scaled by, so that gaps grow in a stressed
    market the way real ones do.

    The loop is unavoidable: GARCH variance, the AR(1) drift and the two
    Markov chains each depend on their own previous value.  Every random draw
    is made up-front as an array, so the loop itself is pure arithmetic and
    stays O(n).
    """
    # alpha + beta = 0.97 is a realistically slow decay, and alpha this size is
    # what makes the clustering visible on a chart.  With t(7) shocks the
    # fourth moment stays finite (alpha^2*E[z^4] + 2*alpha*beta + beta^2 < 1),
    # so the variance process does not wander off.
    alpha, beta = 0.11, 0.86
    omega = sigma0 * sigma0 * (1.0 - alpha - beta)
    var_cap = (7.0 * sigma0) ** 2       # keeps a fat-tailed shock from exploding

    # Student-t shocks, standardised to unit variance: fatter tails than a
    # normal, which is what makes the extremes on the chart look believable.
    df = 7.0
    shocks = rng.standard_t(df, n) / math.sqrt(df / (df - 2.0))

    # Trend / range regime.  Expected episode lengths of a few hundred bars.
    p_trend_switch = 1.0 / 400.0
    u_trend = rng.random(n)
    phi_trend, phi_range = 0.997, 0.94
    sd_trend = 0.055 * sigma0 * math.sqrt(1.0 - phi_trend ** 2)
    sd_range = 0.020 * sigma0 * math.sqrt(1.0 - phi_range ** 2)
    z_mu = rng.standard_normal(n)

    # Volatility regime: calm, normal, stressed.  The states are rescaled so
    # that their probability-weighted mean *square* is one, which keeps the
    # long-run realised volatility on the number it was calibrated to instead
    # of a few percent above it.
    vol_weights = np.array([0.35, 0.50, 0.15])
    vol_states = np.array([0.72, 1.0, 1.75])
    vol_states = vol_states / math.sqrt(float(np.sum(vol_weights * vol_states ** 2)))
    p_vol_switch = 1.0 / 500.0
    u_vol = rng.random(n)
    k_vol = rng.choice(len(vol_states), size=n, p=vol_weights)

    returns = np.empty(n, dtype="float64")
    sigma_used = np.empty(n, dtype="float64")
    sigma_state = np.empty(n, dtype="float64")

    variance = sigma0 * sigma0
    mu = 0.0
    trending = False
    vol_level = 1.0

    for i in range(n):
        if u_trend[i] < p_trend_switch:
            trending = not trending
        if u_vol[i] < p_vol_switch:
            vol_level = float(vol_states[k_vol[i]])

        if trending:
            mu = phi_trend * mu + sd_trend * z_mu[i]
        else:
            mu = phi_range * mu + sd_range * z_mu[i]

        level = math.sqrt(variance) * vol_level
        sigma = level * vol_season[i]
        returns[i] = drift + mu + sigma * shocks[i]
        sigma_used[i] = sigma
        sigma_state[i] = level

        # GARCH is updated with the *standardised* shock so the intraday
        # seasonality shapes each bar without feeding back into the variance
        # process, which would double-count the time-of-day effect.
        variance = omega + alpha * variance * shocks[i] ** 2 + beta * variance
        if variance > var_cap:
            variance = var_cap

    return returns, sigma_used, sigma_state


def _overnight_gaps(rng: np.random.Generator, new_day: np.ndarray,
                    sigma_state: np.ndarray, bars_per_day: int,
                    profile: SessionProfile) -> np.ndarray:
    """Jumps between one session's close and the next session's open.

    A market that closes overnight gaps every morning; one that never closes
    only really gaps over the weekend, so its gaps are much smaller.  Gaps are
    scaled by the volatility *regime* rather than by a constant, because a
    market that is moving 3 percent a day does not open 0.2 percent away from
    where it closed -- and because a constant would dilute the volatility
    clustering that the rest of the process works to produce.
    """
    gaps = np.zeros(new_day.size, dtype="float64")
    idx = np.flatnonzero(new_day)
    if idx.size == 0:
        return gaps

    daily_sigma = sigma_state[idx] * math.sqrt(max(1, bars_per_day))
    if profile.round_the_clock:
        scale, jump_p = _GAP_SCALE_24H, _GAP_JUMP_P_24H
    else:
        scale, jump_p = _GAP_SCALE, _GAP_JUMP_P
    body = rng.standard_normal(idx.size) * daily_sigma * scale

    # Roughly one session in sixty opens on news rather than on drift.
    jump_hit = rng.random(idx.size) < jump_p
    jump_size = (rng.uniform(_GAP_JUMP_LO, _GAP_JUMP_HI, idx.size)
                 * np.where(rng.random(idx.size) < 0.5, -1.0, 1.0)
                 * daily_sigma)
    gaps[idx] = body + np.where(jump_hit, jump_size, 0.0)
    return gaps


def _intrabar_range(rng: np.random.Generator, open_log: np.ndarray,
                    close_log: np.ndarray,
                    sigma_used: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """High and low in log space, guaranteed to bracket the open and close.

    The excursion beyond the body is drawn as a non-negative quantity and then
    split between the two sides, which is what makes
    ``high >= max(open, close)`` and ``low <= min(open, close)`` true by
    construction rather than by repair.  Wicks are biased in the direction of
    the bar, because a bar that closes up usually pushed higher first.
    """
    n = open_log.size
    body_top = np.maximum(open_log, close_log)
    body_bottom = np.minimum(open_log, close_log)
    body = body_top - body_bottom

    # Half-normal excursion plus a share of the body: a bar with a big body
    # has bigger wicks in absolute terms, which is what real bars look like.
    excursion = np.abs(rng.standard_normal(n)) * sigma_used * 0.85 + 0.18 * body

    direction = np.sign(close_log - open_log)
    share = np.clip(rng.beta(2.4, 2.4, n) + 0.12 * direction, 0.05, 0.95)

    high_log = body_top + share * excursion
    low_log = body_bottom - (1.0 - share) * excursion
    return high_log, low_log


def _volume(rng: np.random.Generator, returns: np.ndarray, sigma_used: np.ndarray,
            turnover_season: np.ndarray, daily_volume: float, bars_per_day: int,
            instrument: Instrument) -> np.ndarray:
    """Volume that rises with the time of day and with the size of the move.

    Real volume and absolute return are strongly positively correlated; the
    lognormal factor supplies the dispersion that stops the relationship from
    looking like a straight line.
    """
    per_bar = max(daily_volume / max(1, bars_per_day), 1.0)
    with np.errstate(divide="ignore", invalid="ignore"):
        standardised = np.abs(np.divide(returns, sigma_used,
                                        out=np.zeros_like(returns),
                                        where=sigma_used > 0))
    standardised = np.clip(standardised, 0.0, 8.0)
    noise = np.exp(rng.normal(0.0, 0.35, returns.size) - 0.5 * 0.35 ** 2)
    raw = per_bar * turnover_season * (0.55 + 0.75 * standardised) * noise

    if instrument.asset_class is AssetClass.CRYPTO:
        # Coins trade in fractions; keep three decimals rather than rounding a
        # thinly traded bar down to a whole coin.
        volume = np.maximum(np.round(raw, 3), 0.001)
    else:
        volume = np.maximum(np.round(raw), 1.0)
    return np.ascontiguousarray(volume, dtype="float64")


def _snap_to_tick(instrument: Instrument, open_: np.ndarray, high: np.ndarray,
                  low: np.ndarray, close: np.ndarray
                  ) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Round every price to the instrument's tick grid.

    Rounding to a grid is monotone, so it cannot invert ``high >= open`` -- but
    the maximum and minimum are re-applied anyway, because an invariant that
    the rest of the application relies on should not depend on a floating-point
    argument being right.
    """
    tick = float(instrument.tick_size)
    if tick > 0:
        open_ = np.round(open_ / tick) * tick
        high = np.round(high / tick) * tick
        low = np.round(low / tick) * tick
        close = np.round(close / tick) * tick
        floor = tick
    else:  # pragma: no cover - Instrument forbids a non-positive tick
        floor = 1e-9

    high = np.maximum.reduce([high, open_, close])
    low = np.minimum.reduce([low, open_, close])
    low = np.maximum(low, floor)
    high = np.maximum(high, low)
    return (np.ascontiguousarray(open_), np.ascontiguousarray(high),
            np.ascontiguousarray(low), np.ascontiguousarray(close))


