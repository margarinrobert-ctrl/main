@dataclass(frozen=True)
class SessionProfile:
    """When an instrument trades, in its own timezone.

    ``round_the_clock`` instruments (spot FX, crypto) trade every hour of a
    weekday; the rest trade a bounded session, which is what produces the
    U-shaped intraday volatility curve.
    """

    timezone: str
    open_minute: int
    """Minutes after local midnight when the session opens."""
    close_minute: int
    """Minutes after local midnight when it closes; bars stop before this."""
    round_the_clock: bool = False
    week_close_minute: int | None = None
    """Local minute on Friday after which the market is shut for the weekend.

    Spot FX runs continuously from Monday morning to 17:00 New York on Friday,
    so without this a round-the-clock instrument would be given Friday evening
    bars that the real market does not have.
    """

    @property
    def length_minutes(self) -> int:
        return max(1, self.close_minute - self.open_minute)


def session_for(instrument: Instrument) -> SessionProfile:
    """The trading session used when generating bars for an instrument.

    Deliberately simple: US regular hours for shares, the CME regular-hours
    window for futures, and a full weekday for spot FX, metals and crypto.
    Generating the whole Globex session would add an overnight period whose
    thin liquidity this generator does not model anyway.
    """
    cls = instrument.asset_class
    if cls is AssetClass.EQUITY:
        return SessionProfile("America/New_York", 9 * 60 + 30, 16 * 60)
    if cls is AssetClass.FUTURES:
        # CME index and commodity regular hours, Chicago time.
        return SessionProfile("America/Chicago", 8 * 60 + 30, 15 * 60)
    if cls is AssetClass.INDEX_CFD:
        return SessionProfile("America/New_York", 9 * 60 + 30, 16 * 60)
    if cls is AssetClass.CRYPTO:
        return SessionProfile("UTC", 0, 24 * 60, round_the_clock=True)
    # Spot FX and spot metals: a full weekday in the timezone the instrument
    # names, which for the seeded catalogue is New York, ending at the 17:00
    # Friday close that the whole market observes.
    return SessionProfile(instrument.timezone or "UTC", 0, 24 * 60,
                          round_the_clock=True, week_close_minute=17 * 60)


def _bars_per_session(profile: SessionProfile, timeframe: Timeframe) -> int:
    """How many bars of this timeframe fit in one session."""
    seconds = timeframe.approx_seconds
    if seconds <= 0:  # pragma: no cover - Timeframe forbids it
        raise DataError("A timeframe must be longer than zero seconds.")
    return max(1, int(math.floor(profile.length_minutes * 60.0 / seconds)))


# ---------------------------------------------------------------------------
# Timestamps
# ---------------------------------------------------------------------------


def _session_timestamps(profile: SessionProfile, timeframe: Timeframe,
                        n_bars: int, start: str | datetime | pd.Timestamp) -> np.ndarray:
    """Build ``n_bars`` bar-open timestamps as int64 UTC nanoseconds.

    Weekends are skipped everywhere.  Intraday bars are laid on the session
    grid in the instrument's own timezone, so a session that starts at 09:30
    New York starts at 09:30 New York on both sides of a daylight-saving
    change rather than drifting by an hour.
    """
    if n_bars <= 0:
        raise DataError("A sample needs at least one bar.")
    try:
        first_day = pd.Timestamp(start).normalize()
    except (ValueError, TypeError) as exc:
        raise DataError(f"'{start}' is not a date this application can read.",
                        detail=repr(exc)) from exc
    if first_day.tz is not None:
        first_day = first_day.tz_convert(None)

    if timeframe.unit in (TimeframeUnit.DAY, TimeframeUnit.WEEK, TimeframeUnit.MONTH):
        return _calendar_timestamps(profile, timeframe, n_bars, first_day)

    per_day = _bars_per_session(profile, timeframe)
    step_ns = int(round(timeframe.approx_seconds * 1e9))
    offsets = np.arange(per_day, dtype="int64") * step_ns
    days_needed = int(math.ceil(n_bars / per_day)) + 4  # slack for the Friday close

    # Grow the calendar until it yields enough bars.  It usually fits first
    # time; the loop exists because the Friday close and daylight-saving
    # collisions both remove bars after the grid has been laid out.
    for _ in range(12):
        days = pd.bdate_range(start=first_day, periods=days_needed)
        opens = _localise(days + pd.Timedelta(minutes=profile.open_minute),
                          profile.timezone)
        grid = (opens[:, None] + offsets[None, :]).ravel()

        # A daylight-saving change makes a 24-hour "day" 23 or 25 hours long,
        # so for a round-the-clock instrument the last bar of one day can
        # collide with the first bar of the next.  Sorting and de-duplicating
        # is both the fix and the guarantee that ``ts`` comes out strictly
        # ascending.
        grid = np.unique(grid)
        grid = _apply_week_close(grid, profile)
        if grid.size >= n_bars:
            return np.ascontiguousarray(grid[:n_bars], dtype="int64")
        days_needed = int(days_needed * 1.4) + 5
    raise DataError(  # pragma: no cover - twelve rounds of growth is ample
        "That many bars could not be laid out on this instrument's session "
        "calendar.")


def _apply_week_close(grid: np.ndarray, profile: SessionProfile) -> np.ndarray:
    """Drop bars after the Friday close of a round-the-clock market."""
    if profile.week_close_minute is None or grid.size == 0:
        return grid
    local = pd.to_datetime(grid, utc=True).tz_convert(profile.timezone)
    minutes = local.hour.to_numpy(dtype="int64") * 60 + local.minute.to_numpy(dtype="int64")
    friday = local.weekday.to_numpy() == 4
    return grid[~(friday & (minutes >= profile.week_close_minute))]


def _calendar_timestamps(profile: SessionProfile, timeframe: Timeframe,
                         n_bars: int, first_day: pd.Timestamp) -> np.ndarray:
    """Daily, weekly and monthly bars, stamped at the session open."""
    if timeframe.unit is TimeframeUnit.DAY:
        step = max(1, timeframe.multiplier)
        days = pd.bdate_range(start=first_day, periods=n_bars * step)[::step][:n_bars]
    elif timeframe.unit is TimeframeUnit.WEEK:
        step = max(1, timeframe.multiplier)
        weeks = pd.date_range(start=first_day, periods=n_bars * step, freq="W-MON")
        days = weeks[::step][:n_bars]
    else:
        step = max(1, timeframe.multiplier)
        months = pd.date_range(start=first_day.replace(day=1),
                               periods=n_bars * step + 1, freq="MS")[::step][:n_bars]
        # The first business day of the month is when a monthly bar opens.
        days = pd.DatetimeIndex([
            m if m.weekday() < 5 else m + pd.Timedelta(days=7 - m.weekday())
            for m in months])
    stamps = _localise(pd.DatetimeIndex(days) + pd.Timedelta(minutes=profile.open_minute),
                       profile.timezone)
    if stamps.size < n_bars:  # pragma: no cover - ranges above are generous
        raise DataError("Not enough calendar time to generate that many bars.")
    return np.ascontiguousarray(stamps[:n_bars], dtype="int64")


def _localise(naive: pd.DatetimeIndex, tz_name: str) -> np.ndarray:
    """Read naive local timestamps in ``tz_name`` and return int64 UTC ns.

    ``nonexistent="shift_forward"`` and ``ambiguous=True`` resolve the two
    hours a year that do not exist or happen twice, instead of raising: a
    sample generator has no business failing on a clock change.
    """
    try:
        aware = naive.tz_localize(tz_name, nonexistent="shift_forward", ambiguous=True)
    except (ValueError, KeyError, TypeError) as exc:
        raise DataError(
            f"'{tz_name}' is not a timezone this computer knows about.",
            detail=repr(exc)) from exc
    return aware.tz_convert("UTC").to_numpy(dtype="datetime64[ns]").astype("int64")


# ---------------------------------------------------------------------------
# Seasonality
# ---------------------------------------------------------------------------


def _circular_bump(hours: np.ndarray, centre: float, width: float) -> np.ndarray:
    """A Gaussian bump on the 24-hour clock, so 23:00 is close to 01:00."""
    delta = np.abs(hours - centre)
    delta = np.minimum(delta, 24.0 - delta)
    return np.exp(-0.5 * (delta / width) ** 2)


def _intraday_profiles(minutes: np.ndarray, profile: SessionProfile,
                       instrument: Instrument) -> tuple[np.ndarray, np.ndarray]:
    """Volatility and volume multipliers for each bar, both averaging 1.0.

    For a bounded session this is the familiar U: heavy at the open, quiet
    around lunch, heavy again into the close.  For a round-the-clock
    instrument it is the two-humped FX day -- the London morning and the
    London/New York overlap -- with a quiet Asian afternoon.
    """
    hours = minutes / 60.0
    if profile.round_the_clock:
        if instrument.asset_class is AssetClass.CRYPTO:
            # Crypto is genuinely 24/7 but still wakes up for the US session.
            vol = (0.80 + 0.55 * _circular_bump(hours, 14.0, 3.0)
                   + 0.25 * _circular_bump(hours, 1.5, 2.0))
            turnover = (0.75 + 0.70 * _circular_bump(hours, 14.5, 3.0)
                        + 0.30 * _circular_bump(hours, 2.0, 2.5))
        else:
            # Hours are New York local: 03:00 is the London open, 08:00-12:00
            # the overlap, 19:00-21:00 the thin Sydney/Tokyo handover.
            vol = (0.42 + 0.85 * _circular_bump(hours, 3.0, 1.6)
                   + 1.25 * _circular_bump(hours, 9.5, 2.2)
                   + 0.30 * _circular_bump(hours, 20.0, 2.5))
            turnover = (0.35 + 0.95 * _circular_bump(hours, 3.5, 1.7)
                        + 1.40 * _circular_bump(hours, 10.0, 2.4)
                        + 0.25 * _circular_bump(hours, 20.0, 2.5))
    else:
        span = float(profile.length_minutes)
        x = np.clip((minutes - profile.open_minute) / span, 0.0, 1.0)
        vol = (0.62 + 1.70 * np.exp(-0.5 * (x / 0.10) ** 2)
               + 0.95 * np.exp(-0.5 * ((1.0 - x) / 0.09) ** 2))
        turnover = (0.45 + 1.60 * np.exp(-0.5 * (x / 0.09) ** 2)
                    + 2.10 * np.exp(-0.5 * ((1.0 - x) / 0.07) ** 2))

    # Normalise so the seasonality redistributes activity without changing the
    # total.  Volatility is normalised in *variance* terms -- mean of the
    # squares, not mean of the values -- because scaling returns by a curve
    # whose mean is one still raises their variance by the curve's dispersion,
    # and the calibrated annual volatility has to survive the shaping.
    vol = vol / max(math.sqrt(float(np.mean(vol ** 2))), 1e-12)
    turnover = turnover / max(float(np.mean(turnover)), 1e-12)
    return vol, turnover


