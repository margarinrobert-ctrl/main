def write_sample_csv(path: str | Path, bars: BarSeries | None = None,
                     **generate_kwargs: Any) -> Path:
    """Write a synthetic dataset to a CSV file.

    The first line is :data:`SYNTHETIC_HEADER`, a ``#`` comment that the CSV
    loader skips, so a user who opens the file in a text editor or a
    spreadsheet is told what it is before they read a single price.

    Parameters
    ----------
    path:
        Destination file.
    bars:
        Bars to write.  When omitted they are generated by passing the
        remaining keyword arguments to :func:`generate_sample_data`.

    Returns
    -------
    Path
        The file that was written.
    """
    target = Path(path).expanduser()
    series = bars if bars is not None else generate_sample_data(**generate_kwargs)
    if len(series) == 0:
        raise DataError("There are no bars to write.")
    if not series.meta.get("synthetic"):
        # This function's whole contract is "this file is clearly synthetic";
        # writing real bars through it would put a false warning on real data.
        raise DataError(
            "write_sample_csv only writes generated data. Use the CSV export "
            "in the Reports menu to write real market data.")

    decimals = max(0, int(series.instrument.price_decimals))
    stamps = pd.to_datetime(series.ts, utc=True).strftime("%Y-%m-%d %H:%M:%S%z")
    # Each column is formatted explicitly rather than through ``float_format``,
    # which would print volume with five decimal places on a five-decimal FX
    # instrument.
    price_fmt = f"%.{decimals}f"
    volume_integral = bool(np.all(series.volume == np.round(series.volume)))
    frame = pd.DataFrame({
        "datetime": np.asarray(stamps, dtype=object),
        "open": np.char.mod(price_fmt, series.open),
        "high": np.char.mod(price_fmt, series.high),
        "low": np.char.mod(price_fmt, series.low),
        "close": np.char.mod(price_fmt, series.close),
        "volume": (np.char.mod("%d", series.volume) if volume_integral
                   else np.char.mod("%.3f", series.volume)),
    })

    body = frame.to_csv(index=False, lineterminator="\n")
    text = (f"{SYNTHETIC_HEADER}\n"
            f"# {series.instrument.symbol} {series.timeframe.label}, "
            f"{len(series):,} bars, seed {series.meta.get('seed', 'n/a')}\n"
            f"{body}")
    _atomic_write_text(target, text)
    log.info("Wrote %s (%d bars)", target, len(series))
    return target


def _atomic_write_text(path: Path, text: str) -> None:
    """Write text through a temporary file so a failure cannot truncate a good one."""
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp_name = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp",
                                        dir=str(path.parent))
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(tmp_name, path)
        except BaseException:
            try:
                os.unlink(tmp_name)
            except OSError:
                pass
            raise
    except OSError as exc:
        raise StorageError(
            f"The file {path.name} could not be written to {path.parent}.\n\n"
            f"Check that the folder exists and that there is free space.",
            detail=repr(exc)) from exc


