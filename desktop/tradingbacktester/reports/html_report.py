def _x_axis(ctx: ReportContext, left: float, pw: float, baseline: float, n: int) -> list[str]:
    """Five date labels along the bottom of a time chart."""
    import pandas as pd

    out = [f'<line x1="{left:g}" y1="{baseline:g}" x2="{left + pw:g}" y2="{baseline:g}" '
           f'stroke="{PALETTE.border_strong}" stroke-width="1"/>']
    if n == 0 or len(ctx.ts) == 0:
        return out
    span_days = (int(ctx.ts[-1]) - int(ctx.ts[0])) / 86_400e9
    fmt = "%Y-%m-%d" if span_days > 5 else "%m-%d %H:%M"
    for k in range(5):
        i = int(round((n - 1) * k / 4))
        stamp = pd.Timestamp(int(ctx.ts[min(i, len(ctx.ts) - 1)]), tz="UTC")
        try:
            stamp = stamp.tz_convert(ctx.timezone)
        except Exception:
            pass
        x = left + pw * (i / max(1, n - 1))
        anchor = "start" if k == 0 else "end" if k == 4 else "middle"
        out.append(f'<text x="{x:.1f}" y="{baseline + 15:.1f}" text-anchor="{anchor}" '
                   f'class="axis">{_e(stamp.strftime(fmt))}</text>')
    return out


