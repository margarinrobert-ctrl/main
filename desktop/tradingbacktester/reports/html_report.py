def _section_assumptions(ctx: ReportContext) -> str:
    cfg = ctx.result.config
    ex = cfg.execution
    risk = cfg.risk
    session = cfg.session
    exits = cfg.exits

    if ex.signal_execution is SignalExecution.NEXT_OPEN:
        timing = ("A rule was evaluated on the close of a bar and the resulting order "
                  "filled at the open of the <em>next</em> bar. Nothing in this run "
                  "traded at a price that was not yet knowable when the decision was "
                  "made.")
    else:
        timing = ("Orders filled at the close of the same bar that produced the "
                  "signal. That price was only known once the bar had finished, so "
                  "this setting flatters the result; treat every number in this "
                  "report as an upper bound.")

    priority = {
        "pessimistic": ("When one bar's range covered both the stop and the target, "
                        "the stop was taken. Bar data cannot say which price came "
                        "first, and this is the only assumption that will not "
                        "flatter the result."),
        "optimistic": ("When one bar's range covered both the stop and the target, "
                       "the target was taken. Bar data cannot say which came first, "
                       "and this assumption is the generous one: expect live results "
                       "to be worse."),
        "ohlc_path": ("When one bar's range covered both the stop and the target, an "
                      "open-high-low-close path was assumed — high first on an up "
                      "bar, low first on a down bar — and whichever barrier that "
                      "path reached first was taken. It is a guess about intrabar "
                      "order, not a measurement."),
    }[ex.intrabar_priority.value]

    sizing = _describe_sizing(risk)

    session_text = ("No session filter: every bar in the data was tradeable."
                    if not session.enabled else
                    f"Trading was restricted to {_e(session.start)}–{_e(session.end)} "
                    f"{_e(session.timezone)} on "
                    f"{_e(_weekday_names(session.weekdays))}"
                    + (", and any position still open on the last in-session bar of "
                       "the day was closed there." if session.flat_at_session_end
                       else ", and positions were allowed to carry across the "
                            "session boundary."))

    if risk.max_daily_loss > 0:
        unit = "percent of equity" if risk.max_daily_loss_is_percent else "in cash"
        daily = (f"Trading stopped for the rest of the session day once the day's "
                 f"realised loss reached {risk.max_daily_loss:g} {unit}; any open "
                 f"position was closed at that point and no new position was opened "
                 f"until the next day.")
    else:
        daily = "No daily loss limit was applied."

    if exits.partial_exits:
        pieces = ", ".join(f"{frac * 100:g}% at {r:g}R" for frac, r in exits.partial_exits)
        partial = (f"Partial exits were used ({pieces}). Each piece is reported as its "
                   f"own trade row with its own entry price, exit price and P&amp;L, "
                   f"linked back to the original position by a parent trade id in the "
                   f"CSV export, so the trade count here is larger than the number of "
                   f"positions actually opened.")
    else:
        partial = "No partial exits: every position was closed in one piece."

    paragraphs = [
        ("Order timing", timing),
        ("Intrabar barriers", priority),
        ("Gaps", "If a bar opened beyond a resting stop or target, the fill was taken "
                 "at that opening price and not at the barrier price. A stop does not "
                 "protect you from a gap and this simulation does not pretend it does."),
        ("Costs", f"{_e(_sentence(describe_cost_model(cfg.costs)))}. Every one of "
                  f"these is charged against the trade; there is no setting in which "
                  f"transacting pays the account."),
        ("Position sizing", sizing),
        ("Session", session_text),
        ("Daily loss limit", daily),
        ("Partial exits", partial),
    ]
    body = "".join(f'<div class="assume"><h3>{_e(title)}</h3><p>{text}</p></div>'
                   for title, text in paragraphs)

    limits = (
        "<p>What this simulation cannot model, at all: your position in the order "
        "queue, partial fills, the latency between your machine and the exchange, "
        "how much size the book would really have absorbed, the impact your own "
        "order would have had on the price, and whether the instrument could have "
        "been shorted at that moment. It assumes every order you sent was filled in "
        "full at a price derived from a bar that has already happened.</p>"
        "<p>And it cannot model you. The result above is one path through one "
        "sample of history, chosen by a person who could see that history. If this "
        "configuration is the best of many that were tried, the number that matters "
        "is not the profit — it is how many were tried. See the Backtesting "
        "Assumptions document in Help for the full account.</p>")

    return ('<section class="card"><h2>How this was simulated</h2>'
            f'<div class="assume-grid">{body}</div>'
            f'<div class="limits"><h3>Limits</h3>{limits}</div></section>')


