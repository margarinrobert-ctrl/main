def export_html_report(result: BacktestResult, path: str | Path) -> str:
    """Write a complete, self-contained HTML report; returns the path written."""
    target = Path(path)
    document = build_html_report(result)
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(document, encoding="utf-8")
    except OSError as exc:
        raise ReportError(
            f"The report could not be written to {target}. Check that the folder "
            f"exists and that you have permission to write there.",
            detail=f"{type(exc).__name__}: {exc}") from exc
    log.info("Wrote HTML report (%d characters) to %s", len(document), target)
    return str(target)


def build_html_report(result: BacktestResult) -> str:
    """The whole document as a string.  Separated so it can be tested without I/O."""
    ctx = ReportContext(result)
    body = "\n".join((
        _section_header(ctx),
        _section_headline(ctx),
        _section_warnings(ctx),
        _section_charts(ctx),
        _section_metrics(ctx),
        _section_periodic(ctx),
        _section_exits(ctx),
        _section_montecarlo(ctx),
        _section_trades(ctx),
        _section_assumptions(ctx),
    ))
    title = _e(f"{result.strategy_name or 'Backtest'} — "
               f"{result.instrument_symbol or ''} {result.timeframe_label or ''}".strip())
    return (
        "<!DOCTYPE html>\n"
        '<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"<title>{title}</title>\n"
        f"<style>\n{_css()}\n</style>\n</head>\n"
        f'<body>\n<div class="page">\n{body}\n</div>\n</body>\n</html>\n'
    )


