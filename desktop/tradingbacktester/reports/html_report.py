def _describe_sizing(risk: Any) -> str:
    mode = risk.sizing_mode
    if mode is SizingMode.FIXED_UNITS:
        text = f"Every position was {risk.fixed_units:g} units."
    elif mode is SizingMode.FIXED_CASH:
        text = (f"Every position was sized to about {risk.fixed_cash:,.0f} of notional "
                f"at the entry price.")
    elif mode is SizingMode.PERCENT_EQUITY:
        text = (f"Every position used {risk.percent_equity:g}% of account equity as "
                f"notional, so size grew with the account and shrank after losses.")
    elif mode is SizingMode.RISK_PERCENT:
        text = (f"Size was set so that the distance from entry to the initial stop "
                f"was worth {risk.risk_percent:g}% of equity. Without a stop there is "
                f"no risk to size against and no position was taken.")
    else:
        text = (f"Size targeted {risk.volatility_target_percent:g}% of equity of "
                f"per-bar volatility, using a {risk.volatility_atr_period}-period ATR "
                f"as the volatility estimate.")
    if risk.use_margin:
        margin = (f"{risk.margin_per_unit:,.2f} per unit" if risk.margin_per_unit > 0
                  else f"{risk.margin_percent:g}% of notional")
        text += (f" Positions were margined at {margin}; a position that could not be "
                 f"margined was not opened.")
    else:
        text += " Positions had to be paid for in full from available cash."
    if risk.max_position_units > 0:
        text += f" Size was capped at {risk.max_position_units:g} units."
    text += (f" At most {risk.max_concurrent_positions} position(s) could be open at "
             f"once. Sizing changes the scale of a result; it does not create an edge.")
    return text


def _weekday_names(days: Iterable[int]) -> str:
    names = ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday",
             "Saturday", "Sunday")
    picked = [names[d] for d in sorted(set(int(d) for d in days)) if 0 <= d < 7]
    if not picked:
        return "no weekdays"
    if len(picked) == 1:
        return picked[0]
    return ", ".join(picked[:-1]) + " and " + picked[-1]


