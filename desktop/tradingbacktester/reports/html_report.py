def _section_header(ctx: ReportContext) -> str:
    rows = "".join(
        f'<div class="meta-item"><span class="meta-label">{_e(label)}</span>'
        f'<span class="meta-value">{_e(value)}</span></div>'
        for label, value in run_header_fields(ctx.result))
    return (
        '<header class="head">'
        f'<div class="head-title">{_e(ctx.result.strategy_name or "Backtest report")}</div>'
        f'<div class="head-sub">{_e(ctx.result.instrument_symbol or "")} '
        f'{_e(ctx.result.timeframe_label or "")} — backtest report</div>'
        f'<div class="meta">{rows}</div>'
        '</header>')


def _section_headline(ctx: ReportContext) -> str:
    m = ctx.metrics
    cards: list[str] = []
    for key, label, kind, signed in (
            ("net_profit", "Net profit", "money", True),
            ("return_pct", "Return", "pct", True),
            ("max_drawdown_pct", "Max drawdown", "pct", True),
            ("profit_factor", "Profit factor", "ratio", True),
            ("total_trades", "Trades", "int", False),
            ("win_rate", "Win rate", "pct", False),
            ("sharpe_ratio", "Sharpe", "ratio", True),
            ("expectancy", "Expectancy", "money", True)):
        value = m.get(key)
        colour = ctx.colour_for(key, kind, value, signed)
        badge = _badge(ctx, key)
        cards.append(
            f'<div class="kpi"><div class="kpi-label">{_e(label)}{badge}</div>'
            f'<div class="kpi-value" style="color:{colour}">'
            f'{_e(ctx.fmt(value, kind))}</div></div>')
    return f'<section class="kpis">{"".join(cards)}</section>'


def _section_warnings(ctx: ReportContext) -> str:
    items: list[str] = []
    n = int(ctx.metrics.get("total_trades", 0) or 0)
    if n == 0:
        items.append("This run produced no trades. Nothing below describes a "
                     "strategy; it describes an idle account.")
    elif n < 30:
        items.append(f"Only {n} trades. Profit factor, win rate, Sharpe and every "
                     f"other ratio here is dominated by noise at this sample size. "
                     f"Metrics the analytics layer could not stand behind are marked "
                     f"LOW n.")
    items.extend(str(w) for w in (ctx.result.warnings or ()))
    if not items:
        return ""
    body = "".join(f"<li>{_e(text)}</li>" for text in items)
    return ('<section class="card warn"><h2>Warnings</h2>'
            f'<ul class="warn-list">{body}</ul></section>')


