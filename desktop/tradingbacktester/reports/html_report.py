def _equity_chart(ctx: ReportContext) -> str:
    w, h = 1000.0, 320.0
    left, right, top, bottom = 78.0, 14.0, 14.0, 30.0
    pw, ph = w - left - right, h - top - bottom
    n = len(ctx.equity)

    idx = decimate_indices(ctx.equity, _CHART_POINTS)
    lo = float(np.nanmin(np.minimum(ctx.equity, ctx.balance)))
    hi = float(np.nanmax(ctx.peak))
    start = float(ctx.result.config.starting_capital)
    lo, hi = min(lo, start), max(hi, start)
    lo, hi = _pad_range(lo, hi)

    def sx(i: int | float) -> float:
        return left + (pw * (float(i) / max(1, n - 1)))

    def sy(v: float) -> float:
        return top + ph * (hi - float(v)) / (hi - lo)

    parts: list[str] = [f'<svg class="chart" viewBox="0 0 {w:g} {h:g}" '
                        f'preserveAspectRatio="none" role="img" '
                        f'aria-label="Equity curve">']
    parts.append(f'<rect x="{left:g}" y="{top:g}" width="{pw:g}" height="{ph:g}" '
                 f'fill="{PALETTE.panel_bg}"/>')
    for value in _ticks(lo, hi, 5):
        y = sy(value)
        parts.append(f'<line x1="{left:g}" y1="{y:.1f}" x2="{left + pw:g}" y2="{y:.1f}" '
                     f'stroke="{PALETTE.grid}" stroke-width="1"/>')
        parts.append(f'<text x="{left - 6:g}" y="{y + 3.5:.1f}" text-anchor="end" '
                     f'class="axis">{_e(_money(value, ctx.currency, 0))}</text>')

    # The band between the running peak and equity: the drawdown, shaded.
    peak_pts = [(sx(i), sy(ctx.peak[i])) for i in idx]
    eq_pts = [(sx(i), sy(ctx.equity[i])) for i in idx]
    band = ("M " + " L ".join(f"{x:.1f},{y:.1f}" for x, y in peak_pts)
            + " L " + " L ".join(f"{x:.1f},{y:.1f}" for x, y in reversed(eq_pts)) + " Z")
    parts.append(f'<path d="{band}" fill="{_rgba(PALETTE.drawdown, 0.22)}" '
                 f'stroke="none"/>')

    y_start = sy(start)
    parts.append(f'<line x1="{left:g}" y1="{y_start:.1f}" x2="{left + pw:g}" '
                 f'y2="{y_start:.1f}" stroke="{PALETTE.border_strong}" '
                 f'stroke-width="1" stroke-dasharray="4 4"/>')
    parts.append(f'<path d="{_polyline([(sx(i), sy(ctx.balance[i])) for i in idx])}" '
                 f'fill="none" stroke="{PALETTE.balance}" stroke-width="1.2" '
                 f'stroke-dasharray="3 3" opacity="0.85"/>')
    parts.append(f'<path d="{_polyline(eq_pts)}" fill="none" '
                 f'stroke="{PALETTE.equity}" stroke-width="1.8" '
                 f'stroke-linejoin="round"/>')
    parts.extend(_x_axis(ctx, left, pw, top + ph, n))
    parts.append("</svg>")
    return "".join(parts)


