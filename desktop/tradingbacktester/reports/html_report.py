def _section_metrics(ctx: ReportContext) -> str:
    blocks: list[str] = []
    for title, entries in METRIC_GROUPS:
        rows: list[str] = []
        for key, label, kind, signed, explanation in entries:
            value = ctx.metrics.get(key)
            colour = ctx.colour_for(key, kind, value, signed)
            state = ctx.reliability.get(key, "ok")
            if state == "unavailable":
                colour = PALETTE.text_muted
            note = ctx.reliability_notes.get(key, "") or explanation
            rows.append(
                f'<tr{_title_attr(note)}><th scope="row">{_e(label)}'
                f'{_badge(ctx, key)}</th>'
                f'<td class="num" style="color:{colour}">{_e(ctx.fmt(value, kind))}</td></tr>')
        blocks.append(f'<div class="metric-group"><h3>{_e(title)}</h3>'
                      f'<table class="metrics">{"".join(rows)}</table></div>')
    legend = (
        f'<p class="lede">A <span class="badge low">LOW n</span> badge means the '
        f'sample behind that number is too small to trust it; '
        f'<span class="badge na">N/A</span> means it could not be computed at all, '
        f'usually because its denominator was zero.</p>')
    return ('<section class="card"><h2>Performance statistics</h2>'
            f'{legend}<div class="metric-grid">{"".join(blocks)}</div></section>')


def _section_periodic(ctx: ReportContext) -> str:
    if not ctx.monthly:
        return ""
    heat = _monthly_heatmap(ctx)
    month_table = _monthly_table(ctx)
    year_table = _yearly_table(ctx)
    return ('<section class="card"><h2>Returns by month</h2>'
            '<p class="lede">Each cell is the change in account equity over that '
            'calendar month, measured in the instrument timezone '
            f'({_e(ctx.timezone)}). Months are compounding percentages, not sums of '
            'trade P&amp;L.</p>'
            f'{heat}{month_table}<h3 class="sub">By year</h3>{year_table}</section>')


def _section_exits(ctx: ReportContext) -> str:
    if not ctx.trades:
        return ""
    groups: dict[str, list[Trade]] = {}
    for t in ctx.trades:
        groups.setdefault(t.exit_reason.label, []).append(t)
    total = float(sum(t.net_pnl for t in ctx.trades))
    rows: list[str] = []
    for label, trades in sorted(groups.items(),
                                key=lambda kv: -abs(sum(t.net_pnl for t in kv[1]))):
        net = float(sum(t.net_pnl for t in trades))
        wins = sum(1 for t in trades if t.net_pnl > 0)
        share = len(trades) / len(ctx.trades) * 100.0
        rows.append(
            f"<tr><td>{_e(label)}</td>"
            f'<td class="num">{len(trades):,}</td>'
            f'<td class="num">{_e(_pct(share))}</td>'
            f'<td class="num" style="color:{_sign_colour(net)}">{_e(ctx.money(net))}</td>'
            f'<td class="num">{_e(_pct(wins / len(trades) * 100.0))}</td>'
            f'<td class="num" style="color:{_sign_colour(net)}">'
            f'{_e(ctx.money(net / len(trades)))}</td></tr>')
    rows.append(
        f'<tr class="total"><td>All exits</td><td class="num">{len(ctx.trades):,}</td>'
        f'<td class="num">100.00%</td>'
        f'<td class="num" style="color:{_sign_colour(total)}">{_e(ctx.money(total))}</td>'
        f'<td class="num">'
        f'{_e(_pct(sum(1 for t in ctx.trades if t.net_pnl > 0) / len(ctx.trades) * 100.0))}'
        f'</td><td class="num" style="color:{_sign_colour(total)}">'
        f'{_e(ctx.money(total / len(ctx.trades)))}</td></tr>')
    return ('<section class="card"><h2>Where the money came from</h2>'
            '<p class="lede">Net profit split by the reason each position was closed. '
            'A strategy whose profit arrives at the time stop rather than the target '
            'is a directional bet, whatever its barriers say.</p>'
            '<div class="scroll"><table class="grid"><thead><tr>'
            '<th>Exit reason</th><th class="num">Trades</th><th class="num">Share</th>'
            '<th class="num">Net P&amp;L</th><th class="num">Win rate</th>'
            f'<th class="num">Average</th></tr></thead><tbody>{"".join(rows)}</tbody>'
            '</table></div></section>')


#: Draws for the report's own resampling. Enough for a stable 5th and 95th
#: percentile and still a few hundredths of a second on a normal trade list.
_REPORT_DRAWS = 4000


def _section_montecarlo(ctx: ReportContext) -> str:
    """What else this trade sequence could have done.

    The report is the artefact that gets shared, and a single equity curve
    shared on its own reads as the outcome rather than as one draw from a
    distribution. The block bootstrap is the default here for the same reason
    it is in the dialog: trades cluster by regime, and drawing them
    independently reports a gentler drawdown than the strategy will produce.

    Never fatal: a report that cannot be written because a resampling failed
    would be a worse outcome than a report without this section.
    """
    if len(ctx.trades) < 2:
        return ""
    try:
        from ..analytics.montecarlo import resample_result

        mc = resample_result(ctx.result, method="block", draws=_REPORT_DRAWS)
    except Exception:                       # noqa: BLE001 - see the docstring
        log.debug("Monte Carlo section skipped", exc_info=True)
        return ""

    quantiles = (5, 25, 50, 75, 95)
    rows_by_name = (
        ("Final equity", mc.percentiles(mc.final_equity, quantiles), ctx.money),
        ("Worst drawdown", mc.percentiles(mc.max_drawdown, quantiles), ctx.money),
        ("Worst drawdown %",
         mc.percentiles(mc.max_drawdown_pct, quantiles), _pct),
        ("Trades under water",
         mc.percentiles(mc.longest_drawdown.astype(float), quantiles),
         lambda v: f"{v:,.0f}"),
    )
    rows = []
    for label, values, render in rows_by_name:
        cells = "".join(f'<td class="num">{_e(render(values[q]))}</td>'
                        for q in quantiles)
        rows.append(f"<tr><td>{_e(label)}</td>{cells}</tr>")

    observed = (
        f'<tr class="total"><td>This backtest</td>'
        f'<td class="num" colspan="2">{_e(ctx.money(mc.observed.final_equity))}</td>'
        f'<td class="num" colspan="3">'
        f'{_e(ctx.money(mc.observed.max_drawdown))} drawdown '
        f'({_e(_pct(mc.observed.max_drawdown_pct))})</td></tr>')

    headers = "".join(f'<th class="num">{q}th</th>' for q in quantiles)
    worst = mc.drawdown_at(95)
    summary = (
        f"{_e(f'{mc.losing_probability * 100:.1f}')}% of resampled runs lost "
        f"money and {_e(f'{mc.ruin_probability * 100:.1f}')}% closed below "
        f"{_e(ctx.money(mc.ruin_level))} at some point. "
        f"One run in twenty had a drawdown worse than "
        f"{_e(ctx.money(worst))} — that is the number to size an account "
        f"against, not the {_e(ctx.money(mc.observed.max_drawdown))} this "
        f"backtest happened to produce.")
    return (
        '<section class="card"><h2>What else could have happened</h2>'
        f'<p class="lede">{_REPORT_DRAWS:,} resampled runs over these '
        f'{len(ctx.trades):,} trades, drawn in contiguous blocks of '
        f'{mc.block_size} so that losing streaks survive the resampling. '
        'This describes the range of paths <em>these trades</em> could have '
        'produced. It cannot tell you whether the strategy has an edge: if '
        'these trades came from a rule fitted to this data, every draw is '
        'fitted to it too.</p>'
        '<div class="scroll"><table class="grid"><thead><tr>'
        f'<th>Percentile</th>{headers}</tr></thead>'
        f'<tbody>{"".join(rows)}{observed}</tbody></table></div>'
        f'<p class="lede">{summary}</p></section>')


