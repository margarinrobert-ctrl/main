def _trade_strip(ctx: ReportContext) -> str:
    if not ctx.trades:
        return '<p class="empty">No trades to plot.</p>'
    w, h = 1000.0, 180.0
    left, right, top, bottom = 78.0, 14.0, 12.0, 22.0
    pw, ph = w - left - right, h - top - bottom
    pnl = np.array([float(t.net_pnl) for t in ctx.trades], dtype="float64")
    n = len(pnl)
    span = float(np.nanmax(np.abs(pnl))) if n else 1.0
    span = span if span > 0 else 1.0
    mid = top + ph / 2.0
    bar_w = max(0.6, pw / max(1, n) * 0.9)

    parts = [f'<svg class="chart" viewBox="0 0 {w:g} {h:g}" preserveAspectRatio="none" '
             f'role="img" aria-label="Profit and loss per trade">']
    parts.append(f'<rect x="{left:g}" y="{top:g}" width="{pw:g}" height="{ph:g}" '
                 f'fill="{PALETTE.panel_bg}"/>')
    for frac, value in ((1.0, span), (0.0, 0.0), (-1.0, -span)):
        y = mid - frac * (ph / 2.0 - 4.0)
        parts.append(f'<line x1="{left:g}" y1="{y:.1f}" x2="{left + pw:g}" y2="{y:.1f}" '
                     f'stroke="{PALETTE.grid if frac else PALETTE.border_strong}" '
                     f'stroke-width="1"/>')
        parts.append(f'<text x="{left - 6:g}" y="{y + 3.5:.1f}" text-anchor="end" '
                     f'class="axis">{_e(_money(value, ctx.currency, 0))}</text>')
    for i, v in enumerate(pnl):
        x = left + pw * (i / max(1, n)) + (pw / max(1, n) - bar_w) / 2.0
        height = abs(v) / span * (ph / 2.0 - 4.0)
        y = mid - height if v >= 0 else mid
        colour = PALETTE.long if v > 0 else PALETTE.short if v < 0 else PALETTE.text_muted
        parts.append(f'<rect x="{x:.2f}" y="{y:.2f}" width="{bar_w:.2f}" '
                     f'height="{max(0.6, height):.2f}" fill="{colour}" opacity="0.9"/>')
    parts.append(f'<text x="{left:g}" y="{h - 6:g}" class="axis">trade 1</text>')
    parts.append(f'<text x="{left + pw:g}" y="{h - 6:g}" text-anchor="end" '
                 f'class="axis">trade {n:,}</text>')
    parts.append("</svg>")
    return "".join(parts)


def _monthly_heatmap(ctx: ReportContext) -> str:
    years = sorted({y for y, _m in ctx.monthly})
    cell, gap = 68.0, 3.0
    label_w, head_h = 54.0, 18.0
    w = label_w + 12 * (cell + gap)
    h = head_h + len(years) * (26.0 + gap) + 4.0
    values = [v for v in ctx.monthly.values() if v == v]
    scale = max((abs(v) for v in values), default=1.0) or 1.0

    parts = [f'<svg class="heat" viewBox="0 0 {w:.0f} {h:.0f}" role="img" '
             f'aria-label="Monthly returns heat map">']
    for c, name in enumerate(_MONTHS):
        x = label_w + c * (cell + gap) + cell / 2.0
        parts.append(f'<text x="{x:.1f}" y="{head_h - 6:.1f}" text-anchor="middle" '
                     f'class="axis">{name}</text>')
    for r, year in enumerate(years):
        y = head_h + r * (26.0 + gap)
        parts.append(f'<text x="{label_w - 8:.1f}" y="{y + 17:.1f}" text-anchor="end" '
                     f'class="axis strong">{year}</text>')
        for c in range(12):
            value = ctx.monthly.get((year, c + 1))
            x = label_w + c * (cell + gap)
            if value is None or value != value:
                parts.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{cell:g}" '
                             f'height="26" rx="3" fill="{PALETTE.panel_bg}" '
                             f'stroke="{PALETTE.border}"/>')
                continue
            strength = min(1.0, abs(value) / scale)
            base = PALETTE.long if value >= 0 else PALETTE.short
            parts.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{cell:g}" height="26" '
                         f'rx="3" fill="{_rgba(base, 0.15 + 0.65 * strength)}" '
                         f'stroke="{PALETTE.border}"/>')
            parts.append(f'<text x="{x + cell / 2:.1f}" y="{y + 17:.1f}" '
                         f'text-anchor="middle" class="cellv">'
                         f'{_e(_pct(value, 1, signed=True))}</text>')
    parts.append("</svg>")
    return f'<div class="scroll">{"".join(parts)}</div>'


