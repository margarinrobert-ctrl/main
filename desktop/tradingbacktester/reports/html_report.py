class ReportContext:
    """Everything the sections need, computed once.

    The report never trusts a field's units when it can derive the value itself:
    the underwater series is recomputed from equity and its running maximum
    rather than read from ``curves.drawdown_pct``, so a chart cannot silently be
    drawn a hundred times too large.
    """

    def __init__(self, result: BacktestResult) -> None:
        self.result = result
        self.trades: list[Trade] = list(result.trades)
        self.currency = currency_symbol(result)
        self.decimals = price_decimals(result)
        self.timezone = instrument_timezone(result)
        self.metrics = _metrics_with_fallbacks(result)
        self.reliability: dict[str, str] = dict(
            (result.metrics or {}).get("reliability", {}) or {})
        self.reliability_notes: dict[str, str] = dict(
            (result.metrics or {}).get("reliability_notes", {}) or {})

        curves = result.curves
        if curves is not None and len(curves) > 0:
            self.ts = np.asarray(curves.ts, dtype="int64")
            self.equity = np.asarray(curves.equity, dtype="float64")
            self.balance = np.asarray(curves.balance, dtype="float64")
            self.peak = np.maximum.accumulate(np.nan_to_num(
                self.equity, nan=float(result.config.starting_capital)))
            with np.errstate(divide="ignore", invalid="ignore"):
                under = np.where(self.peak > 0.0, self.equity / self.peak - 1.0, 0.0)
            self.underwater = np.nan_to_num(under, nan=0.0) * 100.0
        else:
            self.ts = np.zeros(0, dtype="int64")
            self.equity = np.zeros(0, dtype="float64")
            self.balance = np.zeros(0, dtype="float64")
            self.peak = np.zeros(0, dtype="float64")
            self.underwater = np.zeros(0, dtype="float64")

        self.monthly, self.yearly = _periodic_returns(result, self.ts, self.equity,
                                                      self.timezone)

    # -- formatting ------------------------------------------------------

    def money(self, value: Any) -> str:
        return _money(value, self.currency)

    def fmt(self, value: Any, kind: str) -> str:
        """Format one metric exactly as the statistics panel would."""
        if value is None:
            return "-"
        if isinstance(value, float) and math.isnan(value):
            return "-"
        if kind == "money":
            return self.money(value)
        if kind == "money_cost":
            return self.money(-abs(float(value))) if value else "-"
        if kind == "pct":
            return _pct(value)
        if kind == "int":
            try:
                return f"{int(value):,}"
            except (TypeError, ValueError):
                return str(value)
        if kind == "int_bars":
            try:
                return f"{int(value):,} bars"
            except (TypeError, ValueError):
                return str(value)
        if kind == "float1":
            return _number(value, 1)
        if kind == "ratio":
            if isinstance(value, float) and math.isinf(value):
                return "∞"
            return _number(value, 2)
        if kind == "duration":
            return _duration(value)
        if kind == "points":
            return _number(value, self.decimals)
        return str(value)

    def colour_for(self, key: str, kind: str, value: Any, signed: bool) -> str:
        """The statistics panel's colour rule, so the two agree on sign."""
        if not signed or not isinstance(value, (int, float)) or isinstance(value, bool):
            return PALETTE.text
        v = float(value)
        if v != v:
            return PALETTE.text_muted
        if key in ("max_drawdown", "max_drawdown_pct", "gross_loss",
                   "largest_loss", "avg_loss"):
            return PALETTE.short if v != 0 else PALETTE.text_dim
        if kind == "ratio" and key in ("profit_factor", "recovery_factor", "sharpe_ratio",
                                       "sortino_ratio", "calmar_ratio", "sqn"):
            threshold = 1.0 if key in ("profit_factor", "recovery_factor") else 0.0
            return (PALETTE.long if v > threshold else
                    PALETTE.short if v < threshold else PALETTE.text_dim)
        return PALETTE.long if v > 0 else PALETTE.short if v < 0 else PALETTE.text_dim


